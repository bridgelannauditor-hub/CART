create or replace function private.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  requested_type text := coalesce(new.raw_user_meta_data ->> 'account_type', 'Customer');
begin
  if requested_type not in ('Customer', 'Seller') then
    requested_type := 'Customer';
  end if;
  insert into public.profiles (
    auth_user_id, first_name, last_name, email, phone, account_type, shop_name,
    profile_image, created_at
  ) values (
    new.id,
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'first_name'), ''), 'Customer'),
    coalesce(new.raw_user_meta_data ->> 'last_name', ''),
    coalesce(new.email, ''),
    new.phone,
    requested_type,
    nullif(trim(new.raw_user_meta_data ->> 'shop_name'), ''),
    new.raw_user_meta_data ->> 'avatar_url',
    coalesce(new.created_at, now())
  ) on conflict (auth_user_id) do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function private.handle_new_auth_user();

-- Product creation is kept server-controlled through an RPC. Seller ownership
-- and aggregate values never come from the client payload.
create or replace function public.create_product(payload jsonb)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  seller public.profiles%rowtype;
  new_id bigint;
  verification_status text;
  listing_limit integer;
begin
  select * into seller from public.profiles
  where auth_user_id = (select auth.uid()) and account_type = 'Seller';
  if seller.id is null then raise exception 'Only sellers can create products.' using errcode = '42501'; end if;

  verification_status := coalesce(seller.seller_verification ->> 'status', 'under_review');
  if verification_status in ('rejected', 'suspended') then
    raise exception 'Seller verification is required before adding products.' using errcode = '42501';
  end if;
  listing_limit := coalesce((seller.seller_verification ->> 'listingLimit')::integer, 5);
  if verification_status = 'under_review' and
     (select count(*) from public.products where seller_id = seller.id) >= listing_limit then
    raise exception 'Listing limit reached while verification is reviewed.' using errcode = '23514';
  end if;

  insert into public.products (
    seller_id, category_id, category_group, category_name, product_name,
    description, price, stock, image, craft_type, material, occasion,
    is_flash_sale, discount_percent, free_shipping, cod_available,
    making_process, media, tags, pricing_mode, options
  ) values (
    seller.id,
    (payload ->> 'categoryId')::bigint,
    payload ->> 'categoryGroup', payload ->> 'categoryName',
    trim(payload ->> 'productName'), trim(payload ->> 'description'),
    (payload ->> 'price')::numeric, (payload ->> 'stock')::integer,
    coalesce(payload ->> 'image', ''), payload ->> 'craftType',
    payload ->> 'material', payload ->> 'occasion',
    coalesce((payload ->> 'isFlashSale')::boolean, false),
    coalesce((payload ->> 'discountPercent')::integer, 0),
    coalesce((payload ->> 'freeShipping')::boolean, false),
    coalesce((payload ->> 'codAvailable')::boolean, false),
    payload -> 'makingProcess', coalesce(payload -> 'media', '[]'::jsonb),
    coalesce(array(select jsonb_array_elements_text(payload -> 'tags')), '{}'),
    coalesce(payload ->> 'pricingMode', 'single'),
    coalesce(payload -> 'options', '[]'::jsonb)
  ) returning id into new_id;
  return new_id;
end;
$$;
revoke all on function public.create_product(jsonb) from public, anon;
grant execute on function public.create_product(jsonb) to authenticated;

-- Called by the server-only migration utility after explicit legacy IDs are
-- imported. The client roles cannot execute it.
create or replace function public.sync_migration_sequences()
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform setval(pg_get_serial_sequence('public.profiles', 'id'), greatest(coalesce((select max(id) from public.profiles), 1), 1), true);
  perform setval(pg_get_serial_sequence('public.products', 'id'), greatest(coalesce((select max(id) from public.products), 1), 1), true);
  perform setval(pg_get_serial_sequence('public.orders', 'id'), greatest(coalesce((select max(id) from public.orders), 1), 1), true);
  perform setval(pg_get_serial_sequence('public.order_items', 'id'), greatest(coalesce((select max(id) from public.order_items), 1), 1), true);
  perform setval(pg_get_serial_sequence('public.reviews', 'id'), greatest(coalesce((select max(id) from public.reviews), 1), 1), true);
  perform setval(pg_get_serial_sequence('public.shop_visits', 'id'), greatest(coalesce((select max(id) from public.shop_visits), 1), 1), true);
  perform setval(pg_get_serial_sequence('public.delivery_addresses', 'id'), greatest(coalesce((select max(id) from public.delivery_addresses), 1), 1), true);
  perform setval(pg_get_serial_sequence('public.cart_items', 'id'), greatest(coalesce((select max(id) from public.cart_items), 1), 1), true);
  perform setval(pg_get_serial_sequence('public.search_history', 'id'), greatest(coalesce((select max(id) from public.search_history), 1), 1), true);
end;
$$;
revoke all on function public.sync_migration_sequences() from public, anon, authenticated;
grant execute on function public.sync_migration_sequences() to service_role;

