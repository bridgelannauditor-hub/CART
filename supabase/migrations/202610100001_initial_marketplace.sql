create table public.products (
  id bigint generated by default as identity primary key,
  seller_id bigint not null references public.profiles(id) on delete restrict,
  category_id bigint not null,
  category_group text,
  category_name text,
  product_name text not null check (char_length(product_name) between 1 and 200),
  description text not null check (char_length(description) <= 5000),
  price numeric(12,2) not null check (price >= 0),
  stock integer not null check (stock >= 0),
  image text not null default '',
  rating numeric(4,3) not null default 0 check (rating between 0 and 5),
  rating_total numeric(14,3) not null default 0 check (rating_total >= 0),
  review_count integer not null default 0 check (review_count >= 0),
  total_sold integer not null default 0 check (total_sold >= 0),
  craft_type text,
  material text,
  occasion text,
  is_flash_sale boolean not null default false,
  discount_percent integer not null default 0 check (discount_percent between 0 and 100),
  free_shipping boolean not null default false,
  cod_available boolean not null default false,
  making_process jsonb,
  media jsonb not null default '[]'::jsonb check (jsonb_typeof(media) = 'array'),
  tags text[] not null default '{}',
  pricing_mode text not null default 'single' check (pricing_mode in ('single', 'per_image')),
  options jsonb not null default '[]'::jsonb check (jsonb_typeof(options) = 'array'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (pricing_mode = 'single' or jsonb_array_length(options) > 0)
);
