create policy profiles_read_authenticated on public.profiles for select to authenticated using (true);
create policy profiles_update_self on public.profiles for update to authenticated
  using (auth_user_id = (select auth.uid()))
  with check (auth_user_id = (select auth.uid()));

create policy verification_read_self on public.seller_verification_applications for select to authenticated
  using (profile_id = (select private.current_profile_id()));
create policy verification_submit_self on public.seller_verification_applications for insert to authenticated
  with check (profile_id = (select private.current_profile_id()) and status = 'under_review');

create policy categories_read on public.categories for select to authenticated using (true);
create policy products_read on public.products for select to authenticated using (true);
create policy products_update_owner on public.products for update to authenticated
  using (seller_id = (select private.current_profile_id()) and (select private.is_seller()))
  with check (seller_id = (select private.current_profile_id()));
create policy products_delete_owner on public.products for delete to authenticated
  using (seller_id = (select private.current_profile_id()) and (select private.is_seller()));

create policy orders_read_participant on public.orders for select to authenticated
  using (customer_id = (select private.current_profile_id()) or (select private.current_profile_id()) = any(seller_ids));
create policy order_items_read_participant on public.order_items for select to authenticated
  using (exists (select 1 from public.orders o where o.id = order_id and
    (o.customer_id = (select private.current_profile_id()) or (select private.current_profile_id()) = any(o.seller_ids))));

create policy reviews_read on public.reviews for select to authenticated using (true);
create policy reviews_write_eligible on public.reviews for insert to authenticated
  with check (
    customer_id = (select private.current_profile_id()) and exists (
      select 1 from public.order_items oi join public.orders o on o.id = oi.order_id
      where oi.product_id = reviews.product_id
        and o.customer_id = reviews.customer_id
        and oi.status = 'Delivered'
    )
  );
create policy reviews_update_own on public.reviews for update to authenticated
  using (customer_id = (select private.current_profile_id()))
  with check (customer_id = (select private.current_profile_id()));

create policy notifications_read_own on public.notifications for select to authenticated
  using (user_id = (select private.current_profile_id()));
create policy notifications_mark_own on public.notifications for update to authenticated
  using (user_id = (select private.current_profile_id()))
  with check (user_id = (select private.current_profile_id()));

create policy conversations_participant on public.conversations for select to authenticated
  using ((select private.current_profile_id()) = any(participant_ids));
create policy conversations_create_participant on public.conversations for insert to authenticated
  with check ((select private.current_profile_id()) = any(participant_ids));
create policy conversations_update_participant on public.conversations for update to authenticated
  using ((select private.current_profile_id()) = any(participant_ids))
  with check ((select private.current_profile_id()) = any(participant_ids));
create policy messages_participant_read on public.messages for select to authenticated
  using (sender_id = (select private.current_profile_id()) or receiver_id = (select private.current_profile_id()));
create policy messages_sender_insert on public.messages for insert to authenticated
  with check (sender_id = (select private.current_profile_id()) and exists (
    select 1 from public.conversations c where c.id = conversation_id and sender_id = any(c.participant_ids) and receiver_id = any(c.participant_ids)
  ));
create policy messages_participant_update on public.messages for update to authenticated
  using (sender_id = (select private.current_profile_id()) or receiver_id = (select private.current_profile_id()))
  with check (sender_id = (select private.current_profile_id()) or receiver_id = (select private.current_profile_id()));

