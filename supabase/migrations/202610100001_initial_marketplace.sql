create or replace function private.refresh_product_rating()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_product_id bigint;
begin
  target_product_id := case when tg_op = 'DELETE' then old.product_id else new.product_id end;
  update public.products p
  set rating = summary.average_rating,
      rating_total = summary.rating_total,
      review_count = summary.review_count
  from (
    select coalesce(avg(r.rating), 0) as average_rating,
           coalesce(sum(r.rating), 0) as rating_total,
           count(*)::integer as review_count
    from public.reviews r
    where r.product_id = target_product_id
  ) summary
  where p.id = target_product_id;
  return null;
end;
$$;

create trigger reviews_refresh_product_rating
after insert or update or delete on public.reviews
for each row execute function private.refresh_product_rating();

