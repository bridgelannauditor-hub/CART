-- Account warnings: a step before suspension.
--
-- An administrator can warn an account with a category and a message. The
-- warning is kept with the same server-built evidence snapshot as a
-- suspension, is logged in the account history, is delivered to the user as a
-- notification, and must be acknowledged by the user at their next sign-in.
-- The suspend flow shows prior warnings, and the suspension record keeps them.

create table public.account_warnings (
  id bigint generated by default as identity primary key,
  profile_id bigint not null references public.profiles(id) on delete cascade,
  message text not null check (char_length(message) between 3 and 500),
  categories text[] not null default '{}',
  evidence jsonb,
  issued_by uuid,
  issued_at timestamptz not null default now(),
  acknowledged_at timestamptz
);
create index account_warnings_profile_idx
  on public.account_warnings (profile_id, issued_at desc);
alter table public.account_warnings enable row level security;
revoke all on public.account_warnings from public, anon, authenticated;

-- Evidence now also lists earlier warnings.
create or replace function private.account_evidence(target_profile_id bigint)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  with listing as (
    select r.id, r.product_id, p.product_name, r.reason, r.status, r.created_at
    from public.listing_reports r
    join public.products p on p.id = r.product_id
    where p.seller_id = account_evidence.target_profile_id
      and r.status <> 'dismissed'
  ),
  shop as (
    select r.id, r.reason, r.status, r.created_at
    from public.shop_reports r
    where r.shop_id = account_evidence.target_profile_id
      and r.status <> 'dismissed'
  ),
  warned as (
    select w.id, w.message, w.categories, w.issued_at
    from public.account_warnings w
    where w.profile_id = account_evidence.target_profile_id
  )
  select jsonb_build_object(
    'listing_reports', jsonb_build_object(
      'total', (select count(*) from listing),
      'open', (select count(*) from listing where status in ('open', 'reviewing')),
      'by_reason', coalesce(
        (select jsonb_object_agg(g.reason, g.n)
         from (select reason, count(*) as n from listing group by reason) g),
        '{}'::jsonb),
      'items', coalesce(
        (select jsonb_agg(to_jsonb(i))
         from (select id as report_id, product_id, product_name, reason, status, created_at
               from listing order by created_at desc limit 10) i),
        '[]'::jsonb)
    ),
    'shop_reports', jsonb_build_object(
      'total', (select count(*) from shop),
      'open', (select count(*) from shop where status in ('open', 'reviewing')),
      'by_reason', coalesce(
        (select jsonb_object_agg(g.reason, g.n)
         from (select reason, count(*) as n from shop group by reason) g),
        '{}'::jsonb),
      'items', coalesce(
        (select jsonb_agg(to_jsonb(i))
         from (select id as report_id, reason, status, created_at
               from shop order by created_at desc limit 10) i),
        '[]'::jsonb)
    ),
    'warnings', jsonb_build_object(
      'total', (select count(*) from warned),
      'items', coalesce(
        (select jsonb_agg(to_jsonb(i))
         from (select id as warning_id, message, categories, issued_at
               from warned order by issued_at desc limit 5) i),
        '[]'::jsonb)
    ),
    'suggested_categories', (
      select coalesce(jsonb_agg(s.category), '[]'::jsonb)
      from (
        select 'inappropriate_products' as category where exists (select 1 from listing)
        union all
        select 'user_reports' where exists (select 1 from shop)
      ) s
    ),
    'captured_at', now()
  );
$$;
revoke all on function private.account_evidence(bigint) from public, anon, authenticated;

create or replace function public.admin_warn_account(
  target_profile_id bigint,
  message text,
  categories text[]
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  profile_row public.profiles;
  clean_message text := trim(coalesce(admin_warn_account.message, ''));
  clean_categories text[];
  evidence_snapshot jsonb;
  warning_id bigint;
begin
  perform private.require_admin();
  if char_length(clean_message) not between 3 and 500 then
    raise exception 'A warning message is required.' using errcode = '22023';
  end if;
  select coalesce(array_agg(distinct c order by c), '{}')
  into clean_categories
  from unnest(coalesce(admin_warn_account.categories, '{}')) as c;
  if cardinality(clean_categories) = 0 then
    raise exception 'Choose at least one reason category.' using errcode = '22023';
  end if;
  if exists (
    select 1 from unnest(clean_categories) as c
    where c not in ('inappropriate_products', 'user_reports', 'other')
  ) then
    raise exception 'Unknown reason category.' using errcode = '22023';
  end if;
  if target_profile_id = private.current_profile_id() then
    raise exception 'Administrators cannot warn their own account.' using errcode = '42501';
  end if;
  select * into profile_row from public.profiles where id = target_profile_id;
  if not found then
    raise exception 'Account not found.' using errcode = 'P0002';
  end if;
  if exists (
    select 1 from public.admin_users a
    where a.auth_user_id = profile_row.auth_user_id and a.revoked_at is null
  ) then
    raise exception 'Administrator accounts cannot be warned.' using errcode = '42501';
  end if;
  if private.is_suspended(target_profile_id) then
    raise exception 'This account is already suspended.' using errcode = '23514';
  end if;

  evidence_snapshot := private.account_evidence(target_profile_id);
  insert into public.account_warnings
    (profile_id, message, categories, evidence, issued_by)
  values
    (target_profile_id, clean_message, clean_categories, evidence_snapshot, (select auth.uid()))
  returning id into warning_id;

  insert into public.notifications (user_id, created_by_id, title, body, type, related_id)
  values (target_profile_id, private.current_profile_id(), 'Account warning',
          clean_message, 'account_warning', warning_id);

  perform private.write_audit_log(
    'admin', 'account_warned', target_profile_id,
    jsonb_build_object(
      'reason', clean_message,
      'categories', to_jsonb(clean_categories),
      'evidence', evidence_snapshot)
  );
end;
$$;
revoke all on function public.admin_warn_account(bigint, text, text[]) from public, anon;
grant execute on function public.admin_warn_account(bigint, text, text[]) to authenticated;

-- The signed-in user's unacknowledged warnings, oldest first.
create or replace function public.my_warnings()
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(jsonb_agg(to_jsonb(w) order by w.issued_at), '[]'::jsonb)
  from (
    select id, message, categories, issued_at
    from public.account_warnings
    where profile_id = private.current_profile_id() and acknowledged_at is null
  ) w;
$$;
revoke all on function public.my_warnings() from public, anon;
grant execute on function public.my_warnings() to authenticated;

create or replace function public.acknowledge_account_warning(warning_id bigint)
returns void
language sql
security definer
set search_path = ''
as $$
  update public.account_warnings
  set acknowledged_at = now()
  where id = acknowledge_account_warning.warning_id
    and profile_id = private.current_profile_id()
    and acknowledged_at is null;
$$;
revoke all on function public.acknowledge_account_warning(bigint) from public, anon;
grant execute on function public.acknowledge_account_warning(bigint) to authenticated;

-- History includes warnings, with their recorded categories and evidence.
create or replace function public.admin_account_history(
  target_profile_id bigint,
  row_limit integer default 100
)
returns table (
  event_id bigint,
  action text,
  actor_kind text,
  actor_email text,
  reason text,
  occurred_at timestamptz,
  details jsonb
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  perform private.require_admin();
  return query
  select l.id, l.action, l.actor_kind, p.email,
         nullif(trim(coalesce(l.details ->> 'reason', l.details ->> 'note', '')), ''),
         l.created_at,
         case when l.action in ('account_suspended', 'account_restored', 'account_warned')
              then l.details end
  from public.audit_logs l
  left join public.profiles p on p.auth_user_id = l.actor_auth_user_id
  where l.target_profile_id = admin_account_history.target_profile_id
    and l.action in (
      'account_warned', 'account_suspended', 'account_restored',
      'seller_account_suspended', 'seller_account_active', 'seller_account_revoked',
      'application_submitted', 'application_approve', 'application_reject',
      'application_appealed', 'shop_submitted', 'identity_review_resolved'
    )
  order by l.created_at desc, l.id desc
  limit least(greatest(coalesce(admin_account_history.row_limit, 100), 1), 500);
end;
$$;
revoke all on function public.admin_account_history(bigint, integer) from public, anon;
grant execute on function public.admin_account_history(bigint, integer) to authenticated;
