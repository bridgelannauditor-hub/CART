-- Buyer-facing "Report store" reports. Moderation state is service-owned.
create table if not exists public.shop_reports (
  id bigint generated by default as identity primary key,
  shop_id bigint not null references public.profiles(id) on delete cascade,
  reporter_id bigint not null references public.profiles(id) on delete cascade,
  reason text not null check (
    reason in ('not_handmade', 'scam', 'inappropriate', 'impersonation', 'other')
  ),
  details text check (char_length(details) <= 1000),
  status text not null default 'open'
    check (status in ('open', 'reviewing', 'resolved', 'dismissed')),
  created_at timestamptz not null default now(),
  unique (shop_id, reporter_id, reason),
  check (shop_id <> reporter_id)
);

create index if not exists shop_reports_shop_status_idx
  on public.shop_reports (shop_id, status);

alter table public.shop_reports enable row level security;

create policy shop_reports_read_own on public.shop_reports
  for select to authenticated
  using (reporter_id = (select private.current_profile_id()));

create policy shop_reports_create on public.shop_reports
  for insert to authenticated
  with check (
    reporter_id = (select private.current_profile_id()) and status = 'open'
  );

grant select, insert on public.shop_reports to authenticated;
grant usage, select on sequence public.shop_reports_id_seq to authenticated;
