-- Flash Sale campaigns run from the seller Marketing Centre.
--
-- A flash sale is a scheduled, percent-off promotion for an existing product
-- with a proven sales record. The server owns eligibility, pricing, promo stock
-- and per-customer limits; the retired products.is_flash_sale flag is no
-- longer read or writable by clients.

begin;

-- Price history ---------------------------------------------------------------
-- One row per price point whenever a product's prices change. A price point is
-- the single product price, or each picture option for per-picture pricing.

create or replace function private.product_price_points(
  pricing_mode text,
  base_price numeric,
  discount_percent integer,
  options jsonb
)
returns table (price_key text, regular_price numeric, effective_price numeric)
language sql
immutable
set search_path = ''
as $$
  select ''::text,
    round(base_price, 2),
    round(base_price * (100 - discount_percent)::numeric / 100, 2)
  where not (pricing_mode = 'per_image'
             and jsonb_array_length(coalesce(options, '[]'::jsonb)) > 0)
  union all
  select option_value ->> 'id',
    round((option_value ->> 'price')::numeric, 2),
    round((option_value ->> 'price')::numeric
          * (100 - discount_percent)::numeric / 100, 2)
  from jsonb_array_elements(coalesce(options, '[]'::jsonb)) as option_value
  where pricing_mode = 'per_image'
    and jsonb_array_length(coalesce(options, '[]'::jsonb)) > 0;
$$;

create table public.product_price_history (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  price_key text not null,
  regular_price numeric(12,2) not null check (regular_price >= 0),
  effective_price numeric(12,2) not null check (effective_price >= 0),
  recorded_at timestamptz not null default now()
);
create index product_price_history_lookup_idx
  on public.product_price_history (product_id, price_key, recorded_at desc);

alter table public.product_price_history enable row level security;
revoke all on public.product_price_history from public, anon, authenticated;

insert into public.product_price_history
  (product_id, price_key, regular_price, effective_price)
select p.id, pp.price_key, pp.regular_price, pp.effective_price
from public.products p
cross join lateral private.product_price_points(
  p.pricing_mode, p.price, p.discount_percent, p.options
) pp;

create or replace function private.record_product_price_history()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  -- Checkout rewrites options to change option stock; only real price changes
  -- are recorded.
  if tg_op = 'UPDATE' and not exists (
    (select * from private.product_price_points(
       new.pricing_mode, new.price, new.discount_percent, new.options)
     except
     select * from private.product_price_points(
       old.pricing_mode, old.price, old.discount_percent, old.options))
    union all
    (select * from private.product_price_points(
       old.pricing_mode, old.price, old.discount_percent, old.options)
     except
     select * from private.product_price_points(
       new.pricing_mode, new.price, new.discount_percent, new.options))
  ) then
    return new;
  end if;

  insert into public.product_price_history
    (product_id, price_key, regular_price, effective_price)
  select new.id, pp.price_key, pp.regular_price, pp.effective_price
  from private.product_price_points(
    new.pricing_mode, new.price, new.discount_percent, new.options
  ) pp;
  return new;
end;
$$;

create trigger record_product_price_history
after insert or update of price, discount_percent, options, pricing_mode
on public.products
for each row execute function private.record_product_price_history();

-- Flash sales -----------------------------------------------------------------

create table public.flash_sales (
  id bigint generated by default as identity primary key,
  seller_id bigint not null references public.profiles(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete cascade,
  discount_percent integer not null check (discount_percent between 1 and 90),
  promo_stock integer not null check (promo_stock > 0),
  sold integer not null default 0 check (sold >= 0 and sold <= promo_stock),
  per_customer_limit integer not null check (per_customer_limit between 1 and 10),
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  cancelled_at timestamptz,
  created_at timestamptz not null default now(),
  check (ends_at - starts_at between interval '1 hour' and interval '72 hours')
);
create index flash_sales_product_idx on public.flash_sales (product_id, ends_at desc);
create index flash_sales_seller_idx on public.flash_sales (seller_id, starts_at desc);

alter table public.flash_sales enable row level security;
create policy flash_sales_read on public.flash_sales
  for select to authenticated using (true);
revoke all on public.flash_sales from public, anon, authenticated;
grant select on public.flash_sales to authenticated;

alter table public.order_items
  add column flash_sale_id bigint references public.flash_sales(id) on delete set null;
create index order_items_flash_sale_idx
  on public.order_items (flash_sale_id) where flash_sale_id is not null;

-- Prices and the regular discount are locked while a flash sale is scheduled
-- or live: the approved discount cannot be inflated, and the regular price
-- cannot drop below the flash price.
create or replace function private.lock_flash_sale_prices()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if current_setting('role', true) in ('authenticated', 'anon')
     and exists (
       select 1 from public.flash_sales f
       where f.product_id = new.id and f.cancelled_at is null and f.ends_at > now()
     )
     and exists (
       (select * from private.product_price_points(
          new.pricing_mode, new.price, new.discount_percent, new.options)
        except
        select * from private.product_price_points(
          old.pricing_mode, old.price, old.discount_percent, old.options))
       union all
       (select * from private.product_price_points(
          old.pricing_mode, old.price, old.discount_percent, old.options)
        except
        select * from private.product_price_points(
          new.pricing_mode, new.price, new.discount_percent, new.options))
     ) then
    raise exception 'Cancel the flash sale before changing this product''s price or discount.'
      using errcode = '23514';
  end if;
  return new;
end;
$$;

create trigger lock_flash_sale_prices
before update of price, discount_percent, options, pricing_mode on public.products
for each row execute function private.lock_flash_sale_prices();

-- Eligibility -----------------------------------------------------------------
-- Moderate rules: listed at least 7 days, at least 1 delivered sale, and no
-- regular price increase in the last 7 days. The flash price of every price
-- point must beat its lowest effective price of the last 30 days.

create or replace function private.flash_sale_eligibility(target_product_id bigint)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  product_row public.products%rowtype;
  reasons text[] := array[]::text[];
  price_point record;
  low_7 numeric;
  low_30 numeric;
  needed integer;
  min_percent integer := 1;
  price_raised boolean := false;
begin
  select * into product_row from public.products where id = target_product_id;
  if not found then
    return jsonb_build_object(
      'product_id', target_product_id, 'eligible', false,
      'reasons', jsonb_build_array('Product not found.'),
      'min_discount_percent', null, 'max_promo_stock', 0);
  end if;

  if product_row.created_at > now() - interval '7 days' then
    reasons := reasons || 'Listed for less than 7 days.'::text;
  end if;
  if not exists (
    select 1 from public.order_items
    where product_id = product_row.id and status = 'Delivered'
  ) then
    reasons := reasons || 'Needs at least 1 delivered sale.'::text;
  end if;
  if product_row.stock <= 0 then
    reasons := reasons || 'Out of stock.'::text;
  end if;
  if exists (
    select 1 from public.flash_sales
    where product_id = product_row.id and cancelled_at is null and ends_at > now()
  ) then
    reasons := reasons || 'Already has a scheduled or live flash sale.'::text;
  end if;

  for price_point in
    select * from private.product_price_points(
      product_row.pricing_mode, product_row.price,
      product_row.discount_percent, product_row.options)
  loop
    -- Prices in effect during a window: rows recorded inside it, plus the
    -- latest row recorded before it started.
    select min(h.regular_price) into low_7 from (
      select regular_price from public.product_price_history
      where product_id = product_row.id and price_key = price_point.price_key
        and recorded_at > now() - interval '7 days'
      union all
      (select regular_price from public.product_price_history
       where product_id = product_row.id and price_key = price_point.price_key
         and recorded_at <= now() - interval '7 days'
       order by recorded_at desc limit 1)
    ) h;
    if low_7 is not null and price_point.regular_price > low_7 then
      price_raised := true;
    end if;

    select min(h.effective_price) into low_30 from (
      select effective_price from public.product_price_history
      where product_id = product_row.id and price_key = price_point.price_key
        and recorded_at > now() - interval '30 days'
      union all
      (select effective_price from public.product_price_history
       where product_id = product_row.id and price_key = price_point.price_key
         and recorded_at <= now() - interval '30 days'
       order by recorded_at desc limit 1)
    ) h;
    low_30 := least(coalesce(low_30, price_point.effective_price),
                    price_point.effective_price);

    if price_point.regular_price <= 0 then
      needed := 91;
    else
      needed := greatest(
        floor(100 * (1 - low_30 / price_point.regular_price))::integer + 1, 1);
      while needed <= 90 and round(
        price_point.regular_price * (100 - needed)::numeric / 100, 2) >= low_30
      loop
        needed := needed + 1;
      end loop;
    end if;
    min_percent := greatest(min_percent, needed);
  end loop;

  if price_raised then
    reasons := reasons || 'Regular price was raised in the last 7 days.'::text;
  end if;
  if min_percent > 90 then
    reasons := reasons ||
      'Its 30-day low price is too low for a flash discount of up to 90%.'::text;
  end if;

  return jsonb_build_object(
    'product_id', product_row.id,
    'eligible', cardinality(reasons) = 0,
    'reasons', to_jsonb(reasons),
    'min_discount_percent', least(min_percent, 90),
    'max_promo_stock', greatest(product_row.stock, 0));
end;
$$;

-- Seller RPCs -----------------------------------------------------------------

create or replace function public.my_flash_sale_eligibility()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  seller_profile_id bigint := private.current_profile_id();
begin
  if seller_profile_id is null or not private.is_seller() then
    raise exception 'Only approved sellers can run flash sales.' using errcode = '42501';
  end if;
  return coalesce((
    select jsonb_agg(private.flash_sale_eligibility(p.id) order by p.id desc)
    from public.products p where p.seller_id = seller_profile_id
  ), '[]'::jsonb);
end;
$$;

create or replace function public.create_flash_sale(config jsonb)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  seller_profile_id bigint := private.current_profile_id();
  product_row public.products%rowtype;
  eligibility jsonb;
  discount_value integer := (config ->> 'discount_percent')::integer;
  promo_value integer := (config ->> 'promo_stock')::integer;
  limit_value integer := (config ->> 'per_customer_limit')::integer;
  starts timestamptz := (config ->> 'starts_at')::timestamptz;
  ends timestamptz := (config ->> 'ends_at')::timestamptz;
  new_id bigint;
begin
  if seller_profile_id is null or not private.is_seller() then
    raise exception 'Only approved sellers can run flash sales.' using errcode = '42501';
  end if;

  -- Locking the product serializes concurrent requests for the same product.
  select * into product_row from public.products
  where id = (config ->> 'product_id')::bigint for update;
  if not found or product_row.seller_id <> seller_profile_id then
    raise exception 'Product not found.' using errcode = 'P0002';
  end if;

  eligibility := private.flash_sale_eligibility(product_row.id);
  if not (eligibility ->> 'eligible')::boolean then
    raise exception '%', eligibility -> 'reasons' ->> 0 using errcode = '23514';
  end if;
  if discount_value is null
     or discount_value < (eligibility ->> 'min_discount_percent')::integer
     or discount_value > 90 then
    raise exception 'Choose a discount between % and 90 percent.',
      eligibility ->> 'min_discount_percent' using errcode = '22023';
  end if;
  if promo_value is null or promo_value < 1 or promo_value > product_row.stock then
    raise exception 'Flash stock must be between 1 and %.', product_row.stock
      using errcode = '22023';
  end if;
  if limit_value is null or limit_value not between 1 and 10 then
    raise exception 'The purchase limit must be between 1 and 10 per customer.'
      using errcode = '22023';
  end if;
  -- The client asks for at least 1 hour; the server allows for request time.
  if starts is null or ends is null
     or starts < now() + interval '55 minutes' then
    raise exception 'Schedule the flash sale to start at least 1 hour from now.'
      using errcode = '22023';
  end if;
  if starts > now() + interval '30 days' then
    raise exception 'Schedule the flash sale within the next 30 days.'
      using errcode = '22023';
  end if;
  if ends - starts not between interval '1 hour' and interval '72 hours' then
    raise exception 'A flash sale runs for 1 to 72 hours.' using errcode = '22023';
  end if;

  insert into public.flash_sales (
    seller_id, product_id, discount_percent, promo_stock, per_customer_limit,
    starts_at, ends_at
  ) values (
    seller_profile_id, product_row.id, discount_value, promo_value, limit_value,
    starts, ends
  ) returning id into new_id;
  return new_id;
end;
$$;

create or replace function public.cancel_flash_sale(target_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  seller_profile_id bigint := private.current_profile_id();
begin
  if seller_profile_id is null then
    raise exception 'Authentication required.' using errcode = '42501';
  end if;
  update public.flash_sales set cancelled_at = now()
  where id = target_id and seller_id = seller_profile_id
    and cancelled_at is null and ends_at > now();
  if not found then
    raise exception 'This flash sale has already ended or was cancelled.'
      using errcode = '23514';
  end if;
end;
$$;

-- Checkout --------------------------------------------------------------------
-- Same as the current place_order, plus flash sale pricing. A live flash sale
-- replaces the regular discount. When the cart names a flash sale that is no
-- longer available, or the customer's limit would be exceeded, checkout is
-- blocked instead of charging more than the customer was shown.

create or replace function public.place_order(payload jsonb)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  customer_profile public.profiles%rowtype;
  requested jsonb;
  product_row public.products%rowtype;
  flash_row public.flash_sales%rowtype;
  live_flash boolean;
  apply_flash boolean;
  requested_flash bigint;
  bought_quantity integer;
  pending_quantity integer;
  base_price numeric;
  option_row jsonb;
  updated_options jsonb;
  item_price numeric;
  requested_quantity integer;
  requested_option text;
  line_items jsonb := '[]'::jsonb;
  seller_list bigint[] := array[]::bigint[];
  product_list bigint[] := array[]::bigint[];
  subtotal_value numeric := 0;
  discount_value numeric := 0;
  seller_subtotal numeric;
  voucher_discount numeric;
  voucher_pair record;
  voucher_row public.customer_vouchers%rowtype;
  applied_vouchers jsonb := '[]'::jsonb;
  fulfillment jsonb := '{}'::jsonb;
  tracking_value jsonb;
  created_order_id bigint;
  line_item jsonb;
  seller_id_value bigint;
  now_text text := now()::text;
begin
  select * into customer_profile from public.profiles
  where auth_user_id = auth.uid() and account_type = 'Customer';
  if not found then raise exception 'A customer account is required.' using errcode = '42501'; end if;
  if jsonb_typeof(payload -> 'items') <> 'array'
     or jsonb_array_length(payload -> 'items') not between 1 and 30 then
    raise exception 'Choose between 1 and 30 products.' using errcode = '22023';
  end if;
  if payload ->> 'payment_method' not in ('Cash on Delivery', 'GCash', 'Maya', 'Bank Account') then
    raise exception 'Unsupported payment method.' using errcode = '22023';
  end if;
  if coalesce(trim(payload #>> '{delivery_address,fullName}'), '') = ''
     or coalesce(trim(payload #>> '{delivery_address,phone}'), '') = ''
     or coalesce(trim(payload #>> '{delivery_address,line1}'), '') = ''
     or coalesce(trim(payload #>> '{delivery_address,city}'), '') = ''
     or coalesce(trim(payload #>> '{delivery_address,province}'), '') = '' then
    raise exception 'A complete delivery address is required.' using errcode = '22023';
  end if;

  for requested in select value from jsonb_array_elements(payload -> 'items')
  loop
    requested_quantity := (requested ->> 'quantity')::integer;
    requested_option := nullif(trim(requested ->> 'option_id'), '');
    requested_flash := nullif(trim(requested ->> 'flash_sale_id'), '')::bigint;
    if requested_quantity not between 1 and 99 then
      raise exception 'Invalid product quantity.' using errcode = '22023';
    end if;
    select * into product_row from public.products
    where id = (requested ->> 'product_id')::bigint for update;
    if not found then raise exception 'A selected product is unavailable.' using errcode = 'P0002'; end if;

    perform 1 from public.profiles
    where id = product_row.seller_id and account_type = 'Seller';
    if not found then raise exception 'A seller account is unavailable.' using errcode = 'P0002'; end if;

    select * into flash_row from public.flash_sales
    where product_id = product_row.id and cancelled_at is null
      and starts_at <= now() and ends_at > now() and sold < promo_stock
    for update;
    live_flash := found;
    if requested_flash is not null and (not live_flash or flash_row.id <> requested_flash) then
      raise exception 'The flash sale for % has ended or sold out. Review your cart.',
        product_row.product_name using errcode = '23514';
    end if;

    apply_flash := false;
    if live_flash then
      select coalesce(sum(oi.quantity), 0) into bought_quantity
      from public.order_items oi
      join public.orders o on o.id = oi.order_id
      where oi.flash_sale_id = flash_row.id
        and o.customer_id = customer_profile.id
        and oi.status <> 'Cancelled';
      select coalesce(sum((value ->> 'quantity')::integer), 0) into pending_quantity
      from jsonb_array_elements(line_items)
      where (value ->> 'flash_sale_id')::bigint = flash_row.id;
      apply_flash :=
        bought_quantity + pending_quantity + requested_quantity <= flash_row.per_customer_limit
        and flash_row.sold + requested_quantity <= flash_row.promo_stock;
      -- A cart that was shown the flash price must not be charged more.
      if requested_flash is not null and not apply_flash then
        if flash_row.sold + requested_quantity > flash_row.promo_stock then
          raise exception 'Only % flash sale units of % are left.',
            flash_row.promo_stock - flash_row.sold, product_row.product_name
            using errcode = '23514';
        end if;
        raise exception 'The flash sale limit for % is % per customer.',
          product_row.product_name, flash_row.per_customer_limit
          using errcode = '23514';
      end if;
      if apply_flash then
        update public.flash_sales set sold = sold + requested_quantity
        where id = flash_row.id;
      end if;
    end if;

    option_row := null;
    if product_row.pricing_mode = 'per_image' and jsonb_array_length(product_row.options) > 0 then
      select value into option_row from jsonb_array_elements(product_row.options)
      where value ->> 'id' = requested_option limit 1;
      if option_row is null then raise exception 'Choose an available product option.' using errcode = '22023'; end if;
      if (option_row ->> 'stock')::integer < requested_quantity then
        raise exception '% does not have enough stock.', product_row.product_name using errcode = '23514';
      end if;
      base_price := (option_row ->> 'price')::numeric;
      select jsonb_agg(case when value ->> 'id' = requested_option
        then jsonb_set(value, '{stock}', to_jsonb((value ->> 'stock')::integer - requested_quantity))
        else value end) into updated_options
      from jsonb_array_elements(product_row.options);
      update public.products set options = updated_options,
        stock = (select coalesce(sum((value ->> 'stock')::integer), 0)
                 from jsonb_array_elements(updated_options)),
        total_sold = total_sold + requested_quantity
      where id = product_row.id;
    else
      if requested_option is not null then raise exception 'This product option is unavailable.' using errcode = '22023'; end if;
      if product_row.stock < requested_quantity then
        raise exception '% does not have enough stock.', product_row.product_name using errcode = '23514';
      end if;
      base_price := product_row.price;
      update public.products set stock = stock - requested_quantity,
        total_sold = total_sold + requested_quantity where id = product_row.id;
    end if;
    item_price := round(
      base_price * (100 - case when apply_flash then flash_row.discount_percent
                               else product_row.discount_percent end)::numeric / 100,
      2
    );

    line_items := line_items || jsonb_build_array(jsonb_build_object(
      'product_id', product_row.id, 'seller_id', product_row.seller_id,
      'quantity', requested_quantity, 'item_price', round(item_price, 2),
      'product_name', product_row.product_name,
      'product_image', coalesce(option_row ->> 'image', product_row.image, ''),
      'option_id', option_row ->> 'id', 'option_name', option_row ->> 'name',
      'option_image', option_row ->> 'image',
      'flash_sale_id', case when apply_flash then flash_row.id end
    ));
    subtotal_value := subtotal_value + item_price * requested_quantity;
    if array_position(seller_list, product_row.seller_id) is null then
      seller_list := array_append(seller_list, product_row.seller_id);
    end if;
    product_list := array_append(product_list, product_row.id);
  end loop;

  for voucher_pair in select * from jsonb_each_text(coalesce(payload -> 'voucher_ids', '{}'::jsonb))
  loop
    seller_id_value := voucher_pair.key::bigint;
    if array_position(seller_list, seller_id_value) is null then
      raise exception 'Voucher does not match this order.' using errcode = '23514';
    end if;
    select * into voucher_row from public.customer_vouchers
    where id = voucher_pair.value for update;
    if not found or voucher_row.customer_id <> customer_profile.id
       or voucher_row.seller_id <> seller_id_value or voucher_row.order_id is not null
       or voucher_row.expires_at <= now() then
      raise exception 'Voucher is expired, used, or unavailable.' using errcode = '23514';
    end if;
    select coalesce(sum((value ->> 'item_price')::numeric * (value ->> 'quantity')::integer), 0)
    into seller_subtotal from jsonb_array_elements(line_items)
    where (value ->> 'seller_id')::bigint = seller_id_value;
    if seller_subtotal < voucher_row.minimum then
      raise exception 'Voucher minimum purchase was not reached.' using errcode = '23514';
    end if;
    if voucher_row.type = 'percentage' then
      voucher_discount := seller_subtotal * voucher_row.value / 100;
      if voucher_row.maximum is not null then voucher_discount := least(voucher_discount, voucher_row.maximum); end if;
    else voucher_discount := voucher_row.value;
    end if;
    voucher_discount := round(least(voucher_discount, seller_subtotal), 2);
    discount_value := discount_value + voucher_discount;
    applied_vouchers := applied_vouchers || jsonb_build_array(jsonb_build_object(
      'voucherId', voucher_row.id, 'sellerId', seller_id_value, 'discount', voucher_discount));
  end loop;

  tracking_value := jsonb_build_object(
    'courier', '', 'trackingNumber', '', 'estimatedDeliveryDate', '',
    'currentLocation', 'Order placed', 'lastUpdated', now_text,
    'history', jsonb_build_array(jsonb_build_object(
      'status', 'Pending', 'location', 'Order placed', 'date', now_text)));
  foreach seller_id_value in array seller_list loop
    select coalesce(sum((value ->> 'item_price')::numeric * (value ->> 'quantity')::integer), 0)
    into seller_subtotal from jsonb_array_elements(line_items)
    where (value ->> 'seller_id')::bigint = seller_id_value;
    select coalesce(sum((value ->> 'discount')::numeric), 0) into voucher_discount
    from jsonb_array_elements(applied_vouchers)
    where (value ->> 'sellerId')::bigint = seller_id_value;
    fulfillment := jsonb_set(fulfillment, array[seller_id_value::text], jsonb_build_object(
      'status', 'Pending', 'subtotal', round(seller_subtotal, 2),
      'discount', round(voucher_discount, 2),
      'total', round(seller_subtotal - voucher_discount, 2), 'tracking', tracking_value));
  end loop;

  insert into public.orders (
    customer_id, seller_ids, product_ids, subtotal, discount, total, status,
    payment_method, delivery_address, seller_fulfillment, tracking, vouchers
  ) values (
    customer_profile.id, seller_list, product_list, round(subtotal_value, 2),
    round(discount_value, 2), round(subtotal_value - discount_value, 2), 'Pending',
    payload ->> 'payment_method', payload -> 'delivery_address', fulfillment,
    tracking_value, applied_vouchers
  ) returning id into created_order_id;

  for line_item in select value from jsonb_array_elements(line_items) loop
    insert into public.order_items (
      order_id, product_id, seller_id, quantity, item_price, product_name,
      product_image, option_id, option_name, option_image, flash_sale_id
    ) values (
      created_order_id, (line_item ->> 'product_id')::bigint,
      (line_item ->> 'seller_id')::bigint, (line_item ->> 'quantity')::integer,
      (line_item ->> 'item_price')::numeric, line_item ->> 'product_name',
      coalesce(line_item ->> 'product_image', ''), line_item ->> 'option_id',
      line_item ->> 'option_name', line_item ->> 'option_image',
      (line_item ->> 'flash_sale_id')::bigint);
  end loop;
  for line_item in select value from jsonb_array_elements(applied_vouchers) loop
    update public.customer_vouchers set order_id = created_order_id,
      redeemed_at = now(),
      revenue = (select round(coalesce(sum(oi.quantity * oi.item_price), 0) - (line_item ->> 'discount')::numeric, 2)
                 from public.order_items oi where oi.order_id = created_order_id
                   and oi.seller_id = (line_item ->> 'sellerId')::bigint)
    where id = line_item ->> 'voucherId';
  end loop;
  foreach seller_id_value in array seller_list loop
    if coalesce((select (notification_preferences ->> 'pushEnabled')::boolean
                 from public.profiles where id = seller_id_value), true)
       and coalesce((select (notification_preferences ->> 'orderUpdates')::boolean
                     from public.profiles where id = seller_id_value), true) then
      insert into public.notifications (user_id, created_by_id, title, body, type, related_id)
      values (seller_id_value, customer_profile.id, 'New order received',
        'Order #' || created_order_id || ' contains products from your shop.',
        'order', created_order_id);
    end if;
  end loop;
  return created_order_id;
end;
$$;

-- Cancellations return flash sale units ------------------------------------------

create or replace function public.cancel_order_item(target_order_id bigint, target_item_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller_id bigint := private.current_profile_id();
  item_row public.order_items%rowtype;
  product_row public.products%rowtype;
  updated_options jsonb;
begin
  select oi.* into item_row from public.order_items oi
  join public.orders o on o.id = oi.order_id
  where oi.id = target_item_id and oi.order_id = target_order_id
    and o.customer_id = caller_id for update of oi;
  if not found then raise exception 'Order item not found.' using errcode = 'P0002'; end if;
  if item_row.status <> 'Pending' then
    raise exception 'Only pending products can be cancelled.' using errcode = '23514';
  end if;
  update public.order_items set status = 'Cancelled', cancelled_at = now()
  where id = target_item_id;
  select * into product_row from public.products where id = item_row.product_id for update;
  if found and product_row.pricing_mode = 'per_image' and item_row.option_id is not null then
    select jsonb_agg(case when value ->> 'id' = item_row.option_id
      then jsonb_set(value, '{stock}', to_jsonb((value ->> 'stock')::integer + item_row.quantity))
      else value end) into updated_options from jsonb_array_elements(product_row.options);
    update public.products set options = updated_options,
      stock = (select coalesce(sum((value ->> 'stock')::integer), 0) from jsonb_array_elements(updated_options)),
      total_sold = greatest(total_sold - item_row.quantity, 0) where id = product_row.id;
  elsif found then
    update public.products set stock = stock + item_row.quantity,
      total_sold = greatest(total_sold - item_row.quantity, 0) where id = product_row.id;
  end if;
  if item_row.flash_sale_id is not null then
    update public.flash_sales set sold = greatest(sold - item_row.quantity, 0)
    where id = item_row.flash_sale_id;
  end if;
  perform private.recalculate_order(target_order_id);
  insert into public.notifications (user_id, created_by_id, title, body, type, related_id)
  select item_row.seller_id, caller_id, 'Product cancelled from order #' || target_order_id,
    'The customer cancelled "' || item_row.product_name || '".', 'order', target_order_id
  where coalesce((select (notification_preferences ->> 'pushEnabled')::boolean
                  from public.profiles where id = item_row.seller_id), true)
    and coalesce((select (notification_preferences ->> 'orderUpdates')::boolean
                  from public.profiles where id = item_row.seller_id), true);
end;
$$;

create or replace function public.update_seller_order(
  target_order_id bigint,
  new_status text,
  tracking_data jsonb default '{}'::jsonb
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  seller_profile public.profiles%rowtype;
  order_row public.orders%rowtype;
  previous_status text;
  item_row public.order_items%rowtype;
  product_row public.products%rowtype;
  updated_options jsonb;
  seller_tracking jsonb;
  seller_record jsonb;
  fulfillment jsonb;
  history jsonb;
  now_text text := now()::text;
begin
  select * into seller_profile from public.profiles
  where auth_user_id = auth.uid() and account_type = 'Seller';
  if not found then raise exception 'A seller account is required.' using errcode = '42501'; end if;
  select * into order_row from public.orders where id = target_order_id
    and seller_profile.id = any(seller_ids) for update;
  if not found then raise exception 'Order not found.' using errcode = 'P0002'; end if;
  select status into previous_status from public.order_items
  where order_id = target_order_id and seller_id = seller_profile.id and status <> 'Cancelled'
  limit 1;
  if previous_status is null then raise exception 'No active products remain.' using errcode = '23514'; end if;
  if new_status <> previous_status and not (
    (previous_status = 'Pending' and new_status in ('Preparing', 'Cancelled')) or
    (previous_status = 'Preparing' and new_status in ('Shipped', 'Cancelled')) or
    (previous_status = 'Shipped' and new_status = 'Out for Delivery') or
    (previous_status = 'Out for Delivery' and new_status = 'Delivered')
  ) then raise exception 'Invalid order status transition.' using errcode = '23514'; end if;

  if new_status = 'Cancelled' then
    for item_row in select * from public.order_items
      where order_id = target_order_id and seller_id = seller_profile.id and status <> 'Cancelled'
    loop
      select * into product_row from public.products where id = item_row.product_id for update;
      if product_row.pricing_mode = 'per_image' and item_row.option_id is not null then
        select jsonb_agg(case when value ->> 'id' = item_row.option_id
          then jsonb_set(value, '{stock}', to_jsonb((value ->> 'stock')::integer + item_row.quantity))
          else value end) into updated_options from jsonb_array_elements(product_row.options);
        update public.products set options = updated_options,
          stock = (select coalesce(sum((value ->> 'stock')::integer), 0) from jsonb_array_elements(updated_options)),
          total_sold = greatest(total_sold - item_row.quantity, 0) where id = product_row.id;
      else
        update public.products set stock = stock + item_row.quantity,
          total_sold = greatest(total_sold - item_row.quantity, 0) where id = product_row.id;
      end if;
      if item_row.flash_sale_id is not null then
        update public.flash_sales set sold = greatest(sold - item_row.quantity, 0)
        where id = item_row.flash_sale_id;
      end if;
    end loop;
  end if;
  update public.order_items set status = new_status,
    cancelled_at = case when new_status = 'Cancelled' then now() else cancelled_at end
  where order_id = target_order_id and seller_id = seller_profile.id and status <> 'Cancelled';

  fulfillment := order_row.seller_fulfillment;
  seller_record := coalesce(fulfillment -> seller_profile.id::text, '{}'::jsonb);
  seller_tracking := coalesce(seller_record -> 'tracking', '{}'::jsonb);
  history := coalesce(seller_tracking -> 'history', '[]'::jsonb) || jsonb_build_array(
    jsonb_build_object('status', new_status,
      'location', coalesce(tracking_data ->> 'currentLocation', ''), 'date', now_text));
  seller_tracking := seller_tracking || tracking_data || jsonb_build_object(
    'lastUpdated', now_text, 'history', history);
  seller_record := seller_record || jsonb_build_object(
    'status', new_status, 'tracking', seller_tracking);
  fulfillment := jsonb_set(fulfillment, array[seller_profile.id::text], seller_record);
  update public.orders set seller_fulfillment = fulfillment,
    tracking = tracking || jsonb_build_object(
      'currentLocation', coalesce(tracking_data ->> 'currentLocation', ''),
      'lastUpdated', now_text,
      'history', coalesce(tracking -> 'history', '[]'::jsonb) || jsonb_build_array(
        jsonb_build_object('status', new_status,
          'location', coalesce(tracking_data ->> 'currentLocation', ''),
          'date', now_text, 'sellerId', seller_profile.id)))
  where id = target_order_id;
  perform private.recalculate_order(target_order_id);
  insert into public.notifications (user_id, created_by_id, title, body, type, related_id)
  select order_row.customer_id, seller_profile.id, 'Order #' || target_order_id || ' update',
    coalesce(nullif(seller_profile.shop_name, ''), 'A seller') ||
      ' marked their products as "' || new_status || '".',
    'order_status', target_order_id
  where coalesce((select (notification_preferences ->> 'pushEnabled')::boolean
                  from public.profiles where id = order_row.customer_id), true)
    and coalesce((select (notification_preferences ->> 'orderUpdates')::boolean
                  from public.profiles where id = order_row.customer_id), true);
end;
$$;

