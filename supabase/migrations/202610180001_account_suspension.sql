-- Account suspension for customers and sellers.
--
-- An administrator can suspend any non-administrator account with a reason and
-- lift it later. A suspended account cannot place orders, send messages, post
-- reviews, or list/edit products, and orders that include a suspended seller's
-- products are refused. Approved sellers are also suspended as sellers, so
-- the existing seller authorization follows the account.
--
-- Suspension history lives in its own table, readable only through the RPCs
-- below, so the reason is never exposed through the readable profiles table.

create table public.account_suspensions (
  id bigint generated by default as identity primary key,
  profile_id bigint not null references public.profiles(id) on delete cascade,
  reason text not null check (char_length(reason) between 3 and 500),
  suspended_by uuid,
  suspended_at timestamptz not null default now(),
  lifted_at timestamptz,
  lifted_by uuid,
  lift_reason text check (lift_reason is null or char_length(lift_reason) between 3 and 500)
);

create unique index account_suspensions_one_active_idx
  on public.account_suspensions (profile_id) where lifted_at is null;
create index account_suspensions_profile_idx
  on public.account_suspensions (profile_id, suspended_at desc);

alter table public.account_suspensions enable row level security;
revoke all on public.account_suspensions from public, anon, authenticated;

create or replace function private.is_suspended(target_profile_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.account_suspensions
    where profile_id = target_profile_id and lifted_at is null
  );
$$;
revoke all on function private.is_suspended(bigint) from public, anon;
grant execute on function private.is_suspended(bigint) to authenticated;

-- The signed-in user's own status, so the app can explain a suspension.
create or replace function public.my_suspension()
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(
    (select jsonb_build_object('suspended', true, 'reason', s.reason)
     from public.account_suspensions s
     where s.profile_id = private.current_profile_id() and s.lifted_at is null),
    jsonb_build_object('suspended', false)
  );
$$;
revoke all on function public.my_suspension() from public, anon;
grant execute on function public.my_suspension() to authenticated;

create or replace function public.admin_set_account_suspension(
  target_profile_id bigint,
  suspend boolean,
  reason text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  profile_row public.profiles;
  seller_status text;
begin
  perform private.require_admin();
  if char_length(trim(coalesce(reason, ''))) not between 3 and 500 then
    raise exception 'A reason is required.' using errcode = '22023';
  end if;
  if target_profile_id = private.current_profile_id() then
    raise exception 'Administrators cannot suspend their own account.' using errcode = '42501';
  end if;
  select * into profile_row from public.profiles where id = target_profile_id;
  if not found then
    raise exception 'Account not found.' using errcode = 'P0002';
  end if;
  if exists (
    select 1 from public.admin_users a
    where a.auth_user_id = profile_row.auth_user_id and a.revoked_at is null
  ) then
    raise exception 'Administrator accounts cannot be suspended.' using errcode = '42501';
  end if;

  if suspend then
    if private.is_suspended(target_profile_id) then
      raise exception 'This account is already suspended.' using errcode = '23514';
    end if;
    insert into public.account_suspensions (profile_id, reason, suspended_by)
    values (target_profile_id, trim(reason), (select auth.uid()));
  else
    update public.account_suspensions
    set lifted_at = now(), lifted_by = (select auth.uid()), lift_reason = trim(reason)
    where profile_id = target_profile_id and lifted_at is null;
    if not found then
      raise exception 'This account is not suspended.' using errcode = '23514';
    end if;
  end if;

  -- Keep seller authorization in step with the account: only flip states this
  -- function owns, so a revoked seller is never restored by lifting a suspension.
  select status into seller_status from public.seller_accounts
  where profile_id = target_profile_id and approved_by is not null;
  if suspend and seller_status = 'active' then
    perform public.admin_set_seller_account_status(target_profile_id, 'suspended', reason);
  elsif not suspend and seller_status = 'suspended' then
    perform public.admin_set_seller_account_status(target_profile_id, 'active', reason);
  end if;

  perform private.write_audit_log(
    'admin',
    case when suspend then 'account_suspended' else 'account_restored' end,
    target_profile_id,
    jsonb_build_object('reason', trim(reason))
  );
end;
$$;
revoke all on function public.admin_set_account_suspension(bigint, boolean, text)
  from public, anon;
grant execute on function public.admin_set_account_suspension(bigint, boolean, text)
  to authenticated;

-- Enforcement ---------------------------------------------------------------

create or replace function private.block_suspended_account()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if private.is_suspended((to_jsonb(new) ->> tg_argv[0])::bigint) then
    raise exception 'This account is suspended.' using errcode = '42501';
  end if;
  return new;
end;
$$;
revoke all on function private.block_suspended_account() from public, anon, authenticated;

create trigger block_suspended_orders before insert on public.orders
  for each row execute function private.block_suspended_account('customer_id');
create trigger block_suspended_messages before insert on public.messages
  for each row execute function private.block_suspended_account('sender_id');
create trigger block_suspended_reviews before insert on public.reviews
  for each row execute function private.block_suspended_account('customer_id');
create trigger block_suspended_products before insert on public.products
  for each row execute function private.block_suspended_account('seller_id');

-- Edits and deletes of a suspended seller's listings from the client. Checkout
-- and the other security-definer functions bypass RLS and are unaffected.
create policy products_block_suspended_update on public.products
  as restrictive for update to authenticated
  using (not (select private.is_suspended(seller_id)));
create policy products_block_suspended_delete on public.products
  as restrictive for delete to authenticated
  using (not (select private.is_suspended(seller_id)));

-- Buyers cannot order from a suspended seller.
create or replace function private.block_orders_from_suspended_sellers()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if exists (
    select 1 from public.account_suspensions s
    where s.lifted_at is null and s.profile_id = any (new.seller_ids)
  ) then
    raise exception 'A seller in your order is currently unavailable. Remove their products and try again.'
      using errcode = '23514';
  end if;
  return new;
end;
$$;
revoke all on function private.block_orders_from_suspended_sellers()
  from public, anon, authenticated;

create trigger block_orders_from_suspended_sellers before insert on public.orders
  for each row execute function private.block_orders_from_suspended_sellers();

