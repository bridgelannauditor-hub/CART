-- Buyer-facing "Not handmade" reports. Moderation state is service-owned.
create table public.listing_reports (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  reporter_id bigint not null references public.profiles(id) on delete cascade,
  reason text not null check (reason in ('not_handmade', 'counterfeit', 'misleading', 'other')),
  details text check (char_length(details) <= 1000),
  status text not null default 'open' check (status in ('open', 'reviewing', 'resolved', 'dismissed')),
  created_at timestamptz not null default now(),
  unique (product_id, reporter_id, reason)
);
create index listing_reports_product_status_idx
  on public.listing_reports (product_id, status);
alter table public.listing_reports enable row level security;
create policy listing_reports_read_own on public.listing_reports
  for select to authenticated using (reporter_id = (select private.current_profile_id()));
create policy listing_reports_create on public.listing_reports
  for insert to authenticated with check (
    reporter_id = (select private.current_profile_id()) and status = 'open'
  );
grant select, insert on public.listing_reports to authenticated;
grant usage, select on sequence public.listing_reports_id_seq to authenticated;

-- Trust score: 70% successful-delivery rate + 30% dispute-free rate.
-- A seller with no completed history starts neutral at 50, not at zero.
create table public.seller_disputes (
  id bigint generated by default as identity primary key,
  seller_id bigint not null references public.profiles(id) on delete cascade,
  order_id bigint references public.orders(id) on delete set null,
  status text not null default 'open' check (status in ('open', 'seller_fault', 'buyer_fault', 'dismissed')),
  created_at timestamptz not null default now(),
  resolved_at timestamptz
);
create index seller_disputes_seller_idx on public.seller_disputes (seller_id, status);
alter table public.seller_disputes enable row level security;
create policy seller_disputes_read_seller on public.seller_disputes
  for select to authenticated using (seller_id = (select private.current_profile_id()));
grant select on public.seller_disputes to authenticated;

create or replace function private.refresh_seller_trust(target_seller_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  delivered_count numeric;
  cancelled_count numeric;
  seller_fault_count numeric;
  completed_count numeric;
  calculated_score numeric;
begin
  select count(*) filter (where status = 'Delivered'),
         count(*) filter (where status = 'Cancelled')
  into delivered_count, cancelled_count
  from public.order_items where seller_id = target_seller_id;

  select count(*) into seller_fault_count
  from public.seller_disputes
  where seller_id = target_seller_id and status = 'seller_fault';

  completed_count := delivered_count + cancelled_count;
  if completed_count = 0 then
    calculated_score := 50;
  else
    calculated_score :=
      (70 * delivered_count / completed_count) +
      (30 * greatest(delivered_count - seller_fault_count, 0) /
        greatest(delivered_count, 1));
  end if;

  update public.profiles
  set trust_score = round(greatest(0, least(100, calculated_score)), 2)
  where id = target_seller_id and account_type = 'Seller';
end;
$$;

create or replace function private.refresh_seller_trust_trigger()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op <> 'INSERT' then
    perform private.refresh_seller_trust(old.seller_id);
  end if;
  if tg_op <> 'DELETE' and (tg_op = 'INSERT' or new.seller_id is distinct from old.seller_id) then
    perform private.refresh_seller_trust(new.seller_id);
  elsif tg_op = 'UPDATE' then
    perform private.refresh_seller_trust(new.seller_id);
  end if;
  -- This is an AFTER trigger; its return value is ignored.
  return null;
end;
$$;

create trigger order_items_refresh_seller_trust
after insert or update of status or delete on public.order_items
for each row execute function private.refresh_seller_trust_trigger();
create trigger disputes_refresh_seller_trust
after insert or update of status or delete on public.seller_disputes
for each row execute function private.refresh_seller_trust_trigger();

do $$
declare seller_record record;
begin
  for seller_record in
    select id from public.profiles where account_type = 'Seller'
  loop
    perform private.refresh_seller_trust(seller_record.id);
  end loop;
end;
$$;

-- Tier 1 accounts cannot exceed PHP 10,000 of non-cancelled order items per
-- calendar month. The trigger runs inside place_order, so a violation rolls
-- the entire checkout back atomically.
create or replace function private.enforce_tier_one_monthly_sales()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  tier integer;
  month_sales numeric;
begin
  select seller_tier into tier from public.profiles where id = new.seller_id;
  if tier <> 1 or new.status = 'Cancelled' then return new; end if;

  select coalesce(sum(oi.item_price * oi.quantity), 0) into month_sales
  from public.order_items oi
  join public.orders o on o.id = oi.order_id
  where oi.seller_id = new.seller_id
    and oi.status <> 'Cancelled'
    and o.order_date >= date_trunc('month', now())
    and o.order_date < date_trunc('month', now()) + interval '1 month';

  if month_sales + (new.item_price * new.quantity) > 10000 then
    raise exception 'Tier 1 monthly sales limit of PHP 10,000 reached.'
      using errcode = '23514';
  end if;
  return new;
end;
$$;
create trigger enforce_tier_one_monthly_sales
before insert on public.order_items
for each row execute function private.enforce_tier_one_monthly_sales();

create or replace function private.reject_expired_seller_listing()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if exists (
    select 1 from public.profiles
    where id = new.seller_id and is_verified_seller
      and verification_expiry is not null
      and verification_expiry < current_date
  ) then
    raise exception 'Seller verification has expired. Renew it before adding products.'
      using errcode = '42501';
  end if;
  return new;
end;
$$;
create trigger reject_expired_seller_listing
before insert on public.products
for each row execute function private.reject_expired_seller_listing();

create or replace function private.is_ph_school_email(candidate text)
returns boolean language sql immutable set search_path = ''
as $$ select lower(coalesce(candidate, '')) ~ '^[^@]+@([a-z0-9-]+\.)+edu\.ph$' $$;

-- Email confirmation is the trust anchor for student school email status.
create or replace function private.sync_confirmed_school_email()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_profile_id bigint;
  is_verified boolean;
begin
  select id into target_profile_id from public.profiles where auth_user_id = new.id;
  if target_profile_id is null then return new; end if;
  is_verified := new.email_confirmed_at is not null and private.is_ph_school_email(new.email);
  update public.seller_verification_applications
  set school_email = case when seller_type = 'student'
        then nullif(lower(new.raw_user_meta_data -> 'seller_verification' ->> 'schoolEmail'), '')
        else null end,
      credential_expiry = case when seller_type = 'student'
        then nullif(new.raw_user_meta_data -> 'seller_verification' ->> 'credentialExpiry', '')::date
        else credential_expiry end,
      seller_tier = case seller_type
        when 'student' then 1 when 'individual' then 2 else 3 end,
      school_email_verified = seller_type = 'student' and is_verified and
        lower(new.raw_user_meta_data -> 'seller_verification' ->> 'schoolEmail') = lower(new.email)
  where profile_id = target_profile_id;
  update public.profiles p
  set school_email_verified = a.school_email_verified,
      seller_tier = a.seller_tier,
      verification_expiry = a.credential_expiry
  from public.seller_verification_applications a
  where p.id = target_profile_id and a.profile_id = p.id;
  return new;
end;
$$;
drop trigger if exists zz_sync_confirmed_school_email on auth.users;
create trigger zz_sync_confirmed_school_email
after insert or update of email_confirmed_at, email on auth.users
for each row execute function private.sync_confirmed_school_email();

-- Service-only moderation endpoint for KYC/admin tooling.
create or replace function public.review_seller_verification(
  target_profile_id bigint,
  approve boolean,
  expires_on date default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  application public.seller_verification_applications%rowtype;
  new_status text := case when approve then 'approved' else 'rejected' end;
begin
  select * into application from public.seller_verification_applications
  where profile_id = target_profile_id for update;
  if not found then raise exception 'Verification application not found.' using errcode = 'P0002'; end if;
  if approve and application.seller_type = 'student' and
     (not application.school_email_verified or expires_on is null or expires_on <= current_date) then
    raise exception 'Student approval requires a verified school email and future expiry.'
      using errcode = '23514';
  end if;

  update public.seller_verification_applications
  set status = new_status, reviewed_at = now(),
      credential_expiry = coalesce(expires_on, credential_expiry)
  where profile_id = target_profile_id;

  update public.profiles
  set is_verified_seller = approve,
      seller_tier = application.seller_tier,
      school_email_verified = application.school_email_verified,
      verification_expiry = case when approve then coalesce(expires_on, application.credential_expiry) else null end,
      seller_verification = coalesce(seller_verification, '{}'::jsonb) || jsonb_build_object(
        'sellerType', application.seller_type,
        'status', new_status,
        'level', case application.seller_tier when 1 then 'student' when 2 then 'micro_business' else 'registered_business' end,
        'listingLimit', application.listing_limit,
        'isVerifiedSeller', approve,
        'sellerTier', application.seller_tier,
        'schoolEmailVerified', application.school_email_verified,
        'verificationExpiry', case when approve then coalesce(expires_on, application.credential_expiry) else null end,
        'trustScore', trust_score
      )
  where id = target_profile_id;
end;
$$;
revoke all on function public.review_seller_verification(bigint, boolean, date)
  from public, anon, authenticated;
grant execute on function public.review_seller_verification(bigint, boolean, date)
  to service_role;

-- Existing client profile updates stay limited to presentation/contact fields;
-- none of the trust columns receive an authenticated UPDATE grant.
grant select (
  is_verified_seller, seller_tier, school_email_verified,
  verification_expiry, trust_score
) on public.profiles to authenticated;

