-- Seller trust and verification hardening.
-- Public trust facts live on profiles; sensitive KYC evidence lives in a
-- separately protected vault. Only service-role review code can approve a
-- seller or change a tier/trust field.

alter table public.profiles
  add column if not exists is_verified_seller boolean not null default false,
  add column if not exists seller_tier integer not null default 1
    check (seller_tier between 1 and 3),
  add column if not exists school_email_verified boolean not null default false,
  add column if not exists verification_expiry date,
  add column if not exists trust_score numeric(5,2) not null default 0
    check (trust_score between 0 and 100);

alter table public.seller_verification_applications
  add column if not exists school_email text,
  add column if not exists school_email_verified boolean not null default false,
  add column if not exists credential_expiry date,
  add column if not exists seller_tier integer not null default 1
    check (seller_tier between 1 and 3);

update public.seller_verification_applications
set seller_tier = case seller_type
  when 'student' then 1 when 'individual' then 2 else 3 end;

update public.profiles p
set seller_tier = a.seller_tier,
    is_verified_seller = a.status = 'approved' and
      (a.seller_type <> 'student' or a.credential_expiry >= current_date),
    school_email_verified = a.school_email_verified,
    verification_expiry = a.credential_expiry
from public.seller_verification_applications a
where a.profile_id = p.id;

create table public.seller_verification_vault (
  profile_id bigint primary key references public.profiles(id) on delete cascade,
  identity_document_path text,
  student_id_path text,
  registration_certificate_path text,
  craft_video_path text,
  face_match_token text,
  payout_match_token text,
  provider_reference text,
  encrypted_metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (
    identity_document_path is not null or student_id_path is not null or
    registration_certificate_path is not null or craft_video_path is not null
  )
);

create trigger seller_verification_vault_updated_at
before update on public.seller_verification_vault
for each row execute function private.set_updated_at();

alter table public.seller_verification_vault enable row level security;
create policy verification_vault_read_self
on public.seller_verification_vault for select to authenticated
using (profile_id = (select private.current_profile_id()));
create policy verification_vault_submit_self
on public.seller_verification_vault for insert to authenticated
with check (
  profile_id = (select private.current_profile_id()) and exists (
    select 1 from public.seller_verification_applications a
    where a.profile_id = seller_verification_vault.profile_id
      and a.status = 'under_review'
  )
);
create policy verification_vault_update_self
on public.seller_verification_vault for update to authenticated
using (profile_id = (select private.current_profile_id()))
with check (
  profile_id = (select private.current_profile_id()) and exists (
    select 1 from public.seller_verification_applications a
    where a.profile_id = seller_verification_vault.profile_id
      and a.status = 'under_review'
  )
);

grant select (
  profile_id, identity_document_path, student_id_path,
  registration_certificate_path, craft_video_path, created_at, updated_at
) on public.seller_verification_vault to authenticated;
grant insert (
  profile_id, identity_document_path, student_id_path,
  registration_certificate_path, craft_video_path
) on public.seller_verification_vault to authenticated;
